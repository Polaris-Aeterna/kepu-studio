_RX = {ch: [(re.compile(f"(?:{p.split('@')[0]})$") if p.split("@")[0] else None,
             re.compile(p.split("@")[1]) if p.split("@")[1] else None, r, why, rw)
            for p, r, why, rw in rules] for ch, rules in RULES.items()}


def rule_at(text: str, i: int) -> tuple[str, str, str] | None:
    """First matching context rule for text[i] -> (reading or '' for safe, why, rewrite)."""
    for before, after, r, why, rw in _RX.get(text[i], ()):
        if (before is None or before.search(text[:i])) and (after is None or after.match(text[i + 1:])):
            return r, why, rw
    return None


def rewrite_hint(ch: str, reading: str) -> str:
    """A rewrite suggestion recorded with any rule for this char and reading."""
    for _, r, _, rw in RULES.get(ch, ()):
        if r == reading and rw:
            return rw
    return ""


# ------------------------------------------------------------------------------------------------ 行
# 来源：《地基之下》production/lib/pronounce.py（2026-10-26）。“行”当“表格的行、证明的第几行”讲念 háng，其余念 xíng。
# 《ETH》里这套规则把“按行合并、行与行之间、起始行、排行榜、同行评审”判成了 xíng：这些已经放进内置词典（词典优先于规则），
# 而且规则和通用词典冲突时会拦下（例如“同行”在词典里是 tóngháng）。
_NUM = "一二三四五六七八九十两几多每这那哪某整首末逐各零〇"
_VAR = r"[A-Za-z0-9′'’)）\]αβγδεζηθικλμνξοπρστυφχψωΓΔΘΛΞΠΣΦΨΩℵ₀₁₂₃]"
_GREEK_ZH = "阿尔法|贝塔|伽马|德尔塔|伊普西隆|epsilon|泽塔|伊塔|西塔|约塔|卡帕|兰姆达|缪|纽|克西|派|柔|西格玛|陶|欧米伽"
_XING_AFTER = re.compile(r"不通|得通|不行|不了|吗|啊|了|呀|得|之有效|动|驶|使|事|程|李|星|政|善|医|贿|凶|窃|刑|军|进|销|囊|为|走")
_BEFORE = [re.compile(r) for r in (
    rf"第\s*(?:{_VAR}|[{_NUM}]|{_GREEK_ZH}|[\s+−-]){{1,6}}$",
    rf"[{_NUM}]$",
    rf"{_VAR}\s*$",
    rf"(?:{_GREEK_ZH})$",
    r"列[和与跟、]?$",
    r"排成$", r"次方$",
)]
_AFTER = [re.compile(r) for r in (r"\s*[和与跟、]?\s*列", r"为[真假]")]
_PAIRS = [(re.compile(a), re.compile(b)) for a, b in (
    (r"的$", r"[数号，。；、：）)]|$"),
    (r"在$", r"[上里]"),
    (r"(?:^|[。，；：“\"（(])$", r"是|分成|对应|代表|表示|记"),
)]


def hang_positions(text: str) -> set[int]:
    """Indices of 行 read háng by the rules (everything else is xíng)."""
    hit = set()
    for i, ch in enumerate(text):
        if ch != "行":
            continue
        before, after = text[:i], text[i + 1:]
        if any(rx.match(after) for rx in _AFTER):
            hit.add(i)
        elif _XING_AFTER.match(after):
            continue
        elif any(rx.search(before) for rx in _BEFORE) or any(a.search(before) and b.match(after) for a, b in _PAIRS):
            hit.add(i)
    return hit
