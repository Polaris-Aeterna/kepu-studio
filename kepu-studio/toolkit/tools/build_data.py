#!/usr/bin/env python3
"""Rebuild kepu/data/words.tsv.gz from jieba's dict.txt and pypinyin's phrase dictionary (both MIT).

    python3 toolkit/tools/build_data.py            # needs: pip install jieba pypinyin

Only the plugin maintainer runs this.  The kepu toolkit itself never imports jieba or pypinyin: it reads the
compact word list written here (word, frequency, and for words that contain a character from
data/polyphones.tsv, the dictionary reading of the whole word).

Reading column: "P <syllables>" = the word is in pypinyin's phrase dictionary (curated, but wrong on many STEM
terms: 方差 chà, 相变 xiāng, 似然 shì …); "J <syllables>" = jieba-only word, reading guessed by pypinyin from
its own segmentation (weak evidence); empty = no inventory character in the word.
"""
from __future__ import annotations

import gzip
import os
import sys
from pathlib import Path

DATA = Path(__file__).resolve().parents[1] / "kepu" / "data"


def main():
    import jieba
    from pypinyin import Style, pinyin
    from pypinyin.constants import PHRASES_DICT, PINYIN_DICT

    inv = {}
    for ln in (DATA / "polyphones.tsv").read_text(encoding="utf-8").splitlines():
        if ln.strip() and not ln.startswith("#"):
            ch = ln.split("\t")[0]
            inv[ch] = 1
    words: dict[str, int] = {}
    with open(os.path.join(os.path.dirname(jieba.__file__), "dict.txt"), encoding="utf-8") as f:
        for ln in f:
            parts = ln.split()
            if len(parts) >= 2 and parts[1].isdigit():
                w = parts[0]
                if 1 <= len(w) <= 8:
                    words[w] = words.get(w, 0) + int(parts[1])
    for w in PHRASES_DICT:
        if w not in words and 2 <= len(w) <= 8:
            words[w] = 5
    out, n_read = [], 0
    for w in sorted(words):
        rd = ""
        if any(c in inv for c in w):
            if w in PHRASES_DICT:
                rd = "P " + " ".join(x[0] for x in PHRASES_DICT[w])
            elif len(w) > 1:
                rd = "J " + " ".join(x[0] for x in pinyin(w, style=Style.TONE))
            n_read += bool(rd)
        out.append(f"{w}\t{words[w]}\t{rd}")
    with gzip.open(DATA / "words.tsv.gz", "wt", encoding="utf-8", compresslevel=9) as f:
        f.write("# word\tfreq\treading  (generated by toolkit/tools/build_data.py from jieba dict.txt + pypinyin; MIT)\n")
        f.write("\n".join(out) + "\n")
    # single-character readings for every inventory and stand-in character (used to validate marks and stand-ins)
    chars = set(inv)
    for ln in (DATA / "standins.tsv").read_text(encoding="utf-8").splitlines():
        if ln.strip() and not ln.startswith("#"):
            chars.update(ln.split("\t")[1])
    with open(DATA / "char_readings.tsv", "w", encoding="utf-8") as f:
        f.write("# char\treadings (pypinyin heteronyms, most common first)\n")
        for c in sorted(chars):
            f.write(f"{c}\t{PINYIN_DICT.get(ord(c), '')}\n")
    size = (DATA / "words.tsv.gz").stat().st_size
    print(f"words: {len(out):,} ({n_read:,} with readings) -> words.tsv.gz {size / 1e6:.2f} MB; "
          f"char_readings: {len(chars)} chars")


if __name__ == "__main__":
    sys.exit(main())
